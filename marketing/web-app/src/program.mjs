export function getWeekById(id) {
  return weeks.find((week) => week.id === Number(id)) ?? null;
}

export function toggleCompletedWeek(completedWeeks, weekId) {
  const id = Number(weekId);
  const current = new Set(completedWeeks.map(Number));
  if (current.has(id)) {
    current.delete(id);
  } else if (getWeekById(id)) {
    current.add(id);
  }
  return [...current].sort((a, b) => a - b);
}

export function getProgress(completedWeeks) {
  const completed = normalizeCompletedWeeks(completedWeeks).length;
  return {
    completed,
    total: weeks.length,
    percent: Math.round((completed / weeks.length) * 100)
  };
}

export function normalizeCompletedWeeks(value) {
  if (!Array.isArray(value)) return [];
  return [...new Set(value.map(Number).filter((id) => getWeekById(id)))].sort((a, b) => a - b);
}

export function getCurrentWeek(completedWeeks) {
  const completed = new Set(normalizeCompletedWeeks(completedWeeks));
  return weeks.find((week) => !completed.has(week.id)) ?? null;
}
