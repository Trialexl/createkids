const pptxgen = require('pptxgenjs');
const path = require('path');

const pptx = new pptxgen();
pptx.layout = 'LAYOUT_WIDE';
pptx.author = 'CreateKids';
pptx.subject = 'Семейная лаборатория творчества';
pptx.title = 'Визионеры — вот кто ваши дети';
pptx.company = 'CreateKids';
pptx.lang = 'ru-RU';
pptx.theme = {
  headFontFace: 'Arial',
  bodyFontFace: 'Arial',
  lang: 'ru-RU'
};
pptx.defineSlideMaster({
  title: 'FULL_IMAGE',
  background: { color: '171A21' },
  objects: []
});

const notes = [
  'CreateKids — семейная лаборатория творчества. Мы не пытаемся заранее угадать профессию ребёнка. Мы создаём условия, в которых он учится замечать, придумывать и воплощать собственные идеи.',
  'Доступность готовых ответов не отменяет знания. Знание становится материалом для постановки вопросов, выбора и создания. ИИ здесь рассматривается как инструмент, а не как замена авторского решения ребёнка.',
  'Нельзя надёжно предсказать конкретные профессии через 10–15 лет. Поэтому ставка делается не на одну специальность, а на авторскую позицию, самостоятельное мышление, предметное мастерство и способность учиться.',
  'Креативность частично зависит от области. Ребёнок может быть оригинален в историях, но пока не владеть рисунком, или хорошо придумывать конструкции, но не интересоваться сценой. Разнообразие помогает обнаружить устойчивый интерес.',
  'Сыну семь лет подходят короткие материальные игры и быстрый результат. Дочери четырнадцать — реальные культурные формы, приватность и более длинный личный проект. Старшая не становится преподавателем младшего.',
  'Творческий цикл включает не только генерацию, но и отбор с улучшением: заметить, придумать варианты, сделать первую версию, проверить эффект и изменить. Незавершённая работа тоже допустимый результат.',
  'Совместная программа работает, когда у каждого остаётся собственное авторство. Родитель поставляет материалы, задаёт вопросы и помогает с техникой по запросу, но не исправляет работу ребёнка.',
  'Это стартовая семейная гипотеза, а не научно установленная дозировка. В загруженную неделю достаточно одной личной или одной совместной сессии. Пропущенные занятия не нужно догонять.',
  'Одна тема может дать разные задачи без сравнения результатов. Семилетний ребёнок придумывает и разыгрывает продукт, подросток исследует аудиторию, визуальный язык и форму представления.',
  'Мы не выставляем общий балл креативности. Наблюдаем факты: самостоятельный выбор, возвращение после окончания, изменение решения, просьбу о новом инструменте и появление собственного проекта.',
  'Пилот охватывает разные медиумы, затем даёт время на ремикс, личный проект и вторую версию. После двенадцати недель ребёнок выбирает направление для углубления и направление для свободного исследования.',
  'Начать можно без дорогого курса: одна коробка материалов и одна семейная игра на этой неделе. Главный критерий — сохранилось ли желание создавать дальше.'
];

for (let i = 1; i <= 12; i++) {
  const slide = pptx.addSlide('FULL_IMAGE');
  const filename = `createkids-slide-${String(i).padStart(2, '0')}.png`;
  slide.addImage({ path: path.join(__dirname, 'slides-png', filename), x: 0, y: 0, w: 13.333, h: 7.5 });
  slide.addNotes(notes[i - 1]);
}

pptx.writeFile({ fileName: path.join(__dirname, 'CreateKids-Визионеры.pptx') });
