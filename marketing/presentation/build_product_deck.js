const pptxgen = require('pptxgenjs');
const path = require('path');

async function main() {
  const pptx = new pptxgen();
  pptx.layout = 'LAYOUT_WIDE';
  pptx.author = 'CreateKids';
  pptx.subject = 'История родителей и происхождение идеи CreateKids';
  pptx.title = 'Почему мы сделали CreateKids';
  pptx.company = 'CreateKids';
  pptx.lang = 'ru-RU';
  pptx.theme = {
    headFontFace: 'Arial',
    bodyFontFace: 'Arial',
    lang: 'ru-RU'
  };
  pptx.defineSlideMaster({
    title: 'FULL_IMAGE',
    background: { color: '171A21' },
    objects: []
  });

  const notes = [
    'Эта презентация — не рассказ о функциях приложения. Это наша история как родителей. У нас двое детей разного возраста, и CreateKids появился из вопроса о том, как помочь им подготовиться к будущему, которого мы сами не можем предсказать.',
    'Всё началось не с идеи создать технологический продукт. Мы думали о будущем собственных детей: что действительно будет им полезно через десять или пятнадцать лет и как развивать это уже сейчас, без попытки заранее выбрать за них профессию или талант.',
    'Нашему сыну семь лет, дочери четырнадцать. Младшему важны игра, движение, материалы в руках и быстрый результат. Подростку нужны самостоятельность, собственный стиль, уважение к личному пространству и настоящие, не детские формы проектов. Одно и то же занятие редко подходит им одинаково.',
    'Мы решили сделать ставку на творчество, но не сводить его к рисованию, музыке или другой отдельной технике. Нам стала важна более широкая способность: создавать новое в разных формах, переносить идеи между областями и постепенно находить собственный способ выражения.',
    'Искусственный интеллект уже умеет быстро создавать типовые тексты, изображения, музыку и код. Это не означает, что знания больше не нужны. Но всё важнее становится умение решить, какой вопрос задать, какую проблему выбрать, какие идеи соединить, какое направление принять и как довести замысел до работающего результата.',
    'Никто не знает точно, какие профессии будут востребованы через десять или пятнадцать лет. Поэтому мы не хотим готовить детей к одному названию профессии или одному правильному пути. Наша родительская гипотеза состоит в том, что самостоятельное мышление и способность создавать пригодятся в разных сценариях будущего.',
    'Постепенно мы поняли, что этот вопрос волнует не только нашу семью. Многие родители тоже пытаются разобраться, какие способности развивать в мире быстрых технологических изменений и как делать это без страха, давления и недоказанных обещаний.',
    'Родители видят, что мир меняется быстрее привычных образовательных маршрутов. Они понимают ценность самостоятельности, воображения и авторского выбора, но часто не знают, как превратить эти понятия в регулярную домашнюю практику. Тревоге нужен не лозунг, а понятное действие.',
    'На практике возникают четыре препятствия. Непонятно, какие направления дать попробовать. Сложно подобрать задания детям разного возраста. Регулярная подготовка снова ложится на взрослого. А готовый образец, оценка и сравнение легко превращают творчество в ещё одну школу с правильными ответами.',
    'Так появилась идея CreateKids: превратить большую тревожную задачу «подготовить ребёнка к будущему» в спокойную семейную практику. Сначала были наш вопрос, принципы и программа. Приложение появилось позже как способ сделать этот ритм доступным другим семьям.',
    'Каждую неделю приложение предлагает короткое задание младшему ребёнку, более самостоятельный проект подростку, общую семейную игру или лабораторию и короткую фиксацию процесса. Формы меняются: рисунок, история, музыка, конструкция, театр, кино, цифровой проект или полезное изобретение.',
    'Через двенадцать недель семья получает не набор одинаковых поделок и не оценку способностей. Она получает карту интересов каждого ребёнка: что он выбирал сам, где дольше удерживал внимание, к чему вернулся без уговоров, что улучшил после неудачи и чем захотел поделиться.',
    'Мы не продаём уроки рисования, дополнительное экранное время или обещание угадать профессию будущего. Мы хотим дать родителю понятный способ действовать в неопределённости, а ребёнку — безопасное место, где можно пробовать, бросать, переделывать, ошибаться и находить своё без сравнения с другими.',
    'Мы не хотим решать за детей, в чём их талант. Мы хотим создать условия, в которых они смогут это обнаружить сами. Будущее нельзя предсказать, но способность замечать возможности, придумывать и создавать можно развивать уже сейчас.'
  ];

  for (let i = 1; i <= 14; i++) {
    const slide = pptx.addSlide('FULL_IMAGE');
    const filename = `createkids-product-${String(i).padStart(2, '0')}.png`;
    slide.addImage({
      path: path.join(__dirname, 'product-slides-png', filename),
      x: 0,
      y: 0,
      w: 13.333,
      h: 7.5
    });
    slide.addNotes(notes[i - 1]);
  }

  await pptx.writeFile({
    fileName: path.join(__dirname, 'CreateKids-Презентация-проекта.pptx')
  });
  console.log('Replaced CreateKids-Презентация-проекта.pptx with the founder story');
}

main().catch((error) => {
  console.error(error);
  process.exit(1);
});
