const pptxgen = require('pptxgenjs');
const path = require('path');

async function main() {
  const pptx = new pptxgen();
  pptx.layout = 'LAYOUT_WIDE';
  pptx.author = 'CreateKids';
  pptx.subject = 'Описание проекта и продукта на основе заметки Идеи.md';
  pptx.title = 'CreateKids — презентация проекта';
  pptx.company = 'CreateKids';
  pptx.lang = 'ru-RU';
  pptx.theme = {
    headFontFace: 'Arial',
    bodyFontFace: 'Arial',
    lang: 'ru-RU'
  };
  pptx.defineSlideMaster({
    title: 'FULL_IMAGE',
    background: { color: '171A21' },
    objects: []
  });

  const notes = [
    'CreateKids — семейное приложение для родителей детей примерно 6–15 лет. Главная позиция бренда: мы не можем честно предсказать профессии будущего, но можем уже сейчас развивать привычку замечать возможности, придумывать варианты, делать первую версию и улучшать её.',
    'Проект появился из личной ситуации основателей: в семье двое детей, семилетний сын и четырнадцатилетняя дочь. Нужна была программа, где младший получает короткую материальную игру, подросток — уважительное личное пространство и настоящий авторский проект, а семья может иногда создавать вместе. Готового маршрута не нашли, поэтому собрали свой.',
    'Искусственный интеллект уже умеет генерировать тексты, изображения, музыку и код. CreateKids не обещает, что творческие профессии защищены от автоматизации. Честная ставка другая: человеку всё равно нужно поставить задачу, придумать направление, выбрать между вариантами, оценить результат и отвечать за финальное решение. ИИ может быть инструментом, но ребёнок остаётся автором.',
    'Родительская тревога превращается в конкретные проблемы. Сложно выбирать кружок, пока ребёнок мало что пробовал. Трудно подобрать одно занятие детям разного возраста. Подготовка отнимает время. А образцы, оценки и сравнение быстро превращают творчество в ещё одну школу. Продукт снимает организационную нагрузку, не забирая у ребёнка авторский выбор.',
    'CreateKids — не тест на врождённый талант. Семья собирает наблюдения за реальным поведением: что ребёнок выбирает сам, где удерживает внимание, что переделывает после неудачи, к чему возвращается и чем хочет поделиться. Через двенадцать недель следующий шаг выбирается по фактам, а не по рекламному буклету кружка.',
    'Каждую неделю приложение даёт одну тему и четыре понятных элемента: короткую задачу младшему ребёнку, более самостоятельный проект подростку, общую семейную лабораторию и короткую рефлексию. Список материалов готовится максимум за пятнадцать минут. В загруженную неделю можно сделать только одну личную или одну семейную сессию; пропуски не нужно догонять.',
    'Экран используется несколько минут: выбрать задание, увидеть следующий шаг, запустить таймер и убрать телефон. Само творчество происходит с бумагой, картоном, звуком, движением, камерой, конструктором или другими материалами. После занятия приложение помогает сохранить артефакт и мысль о следующей версии. Это ответ на возражение о лишнем экранном времени.',
    'Программа даёт попробовать восемь форм создания: рисунок, истории, музыку, конструирование, театр, кино, цифровые проекты и дизайн. Цель разнообразия — не поверхностно пройти всё, а дать ребёнку материал для осознанного выбора и заметить устойчивые интересы в конкретных областях.',
    'У детей разного возраста отдельные задания и равноправные роли. Семилетнему ребёнку подходят быстрые игровые формы и видимый результат. Подростку — собственный стиль, приватность, реальные форматы и более длинный проект. В общем деле старший не становится учителем или няней, а младший — исполнителем чужой идеи.',
    'Методика включает честную работу с влияниями по принципу «Кради как художник»: собрать несколько источников, заметить конкретный приём, попробовать его, соединить с другими идеями, изменить тему, форму, материал или назначение и назвать авторов вдохновения. Продукт учит не создавать из пустоты, но и не принимать точное повторение за авторскую работу.',
    'К концу цикла семья получает цифровую выставку, ленту черновиков и улучшений, карту интересов каждого ребёнка и подсказку для следующего маршрута. Важен не красивый финал, а наблюдаемые сигналы: самостоятельный выбор, возвращение без уговоров, вторая версия, запрос нового инструмента и собственная инициатива.',
    'CreateKids отличается от обычного приложения с уроками. Оно не обучает одной технике, не предлагает повторить единый образец и не оценивает результат. Здесь есть открытые задачи, личные и семейные проекты, разные уровни по возрасту и итоговая цель — найти направления, к которым хочется возвращаться.',
    'Для MVP достаточно онбординга по возрасту и времени, двенадцати недель контента, пошагового режима с таймером, копилки вдохновения, сохранения источников и приёмов, загрузки артефактов, короткой рефлексии, портфолио и итоговой карты интересов. Проверяем три действия: семья начала следующую неделю, ребёнок вернулся к проекту, родителю стало легче проводить занятие без давления.',
    'Лучший вход в продукт — бесплатная первая неделя «Наблюдать и замечать». После первого проекта семья уже понимает механику и ценность. Полный маршрут продаётся разово; после него возможна подписка на тематические сезоны: кино, игры, истории, изобретения. Основные каналы — родительские сообщества, педагоги, блогеры, творческие школы, музеи и семейные мероприятия.',
    'Финальная идея проекта: не решать за ребёнка, в чём его талант, а создать условия, чтобы он обнаружил это через опыт. Ценность CreateKids не только в двенадцати наборах заданий. Она в новой семейной привычке — не ждать готового ответа, а создавать собственный.'
  ];

  for (let i = 1; i <= 15; i++) {
    const slide = pptx.addSlide('FULL_IMAGE');
    const filename = `createkids-product-${String(i).padStart(2, '0')}.png`;
    slide.addImage({
      path: path.join(__dirname, 'product-slides-png', filename),
      x: 0,
      y: 0,
      w: 13.333,
      h: 7.5
    });
    slide.addNotes(notes[i - 1]);
  }

  await pptx.writeFile({
    fileName: path.join(__dirname, 'CreateKids-Презентация-проекта.pptx')
  });
  console.log('Created CreateKids-Презентация-проекта.pptx');
}

main().catch((error) => {
  console.error(error);
  process.exit(1);
});
